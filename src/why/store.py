"""The decision store: plain files under `.why/`, versioned by git alongside the code.

Layout:
    .why/config.yaml          repo settings (language, guard dir, sandbox setup)
    .why/decisions/D-0001.yaml one file per decision
    .why/log.jsonl            every state transition, append-only
    .why/evidence.jsonl       every guard run, append-only
    .why/reports/*.json       upgrade / merge / assumption reports
"""

from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path
from typing import Any, Iterable

import yaml

from .models import TRANSITIONS, Decision, Evidence, now

DEFAULT_CONFIG: dict[str, Any] = {
    "language": "python",
    "guards_dir": "why_guards",
    "python_path": ["."],
    "setup": [],
    "install": [],
    "sandbox": "local",
    "timeout_s": 300,
    "mining": {"days": 90, "max_per_source": 3, "min_confidence": 0.45},
}


class StoreError(RuntimeError):
    pass


def find_root(start: Path | None = None) -> Path:
    """Nearest directory containing `.why/`, else the git top level, else cwd."""
    p = (start or Path.cwd()).resolve()
    for cand in (p, *p.parents):
        if (cand / ".why").is_dir():
            return cand
    try:
        top = subprocess.run(
            ["git", "rev-parse", "--show-toplevel"], cwd=p, capture_output=True, text=True, check=True
        ).stdout.strip()
        return Path(top)
    except (subprocess.CalledProcessError, FileNotFoundError):
        return p


class Store:
    def __init__(self, root: Path):
        self.root = Path(root).resolve()
        self.dir = self.root / ".why"

    # ---- setup -------------------------------------------------------------

    @property
    def exists(self) -> bool:
        return self.dir.is_dir()

    def init(self, **overrides: Any) -> None:
        (self.dir / "decisions").mkdir(parents=True, exist_ok=True)
        (self.dir / "reports").mkdir(exist_ok=True)
        cfg_path = self.dir / "config.yaml"
        if not cfg_path.exists():
            cfg = {**DEFAULT_CONFIG, **{k: v for k, v in overrides.items() if v is not None}}
            cfg_path.write_text(yaml.safe_dump(cfg, sort_keys=False))
        for name in ("log.jsonl", "evidence.jsonl"):
            (self.dir / name).touch()
        ignore = self.dir / ".gitignore"
        if not ignore.exists():
            # Decisions, their history and config are versioned with the code; run output is not.
            ignore.write_text("# Run output, kept locally / on the Why server\nevidence.jsonl\nconsults.jsonl\n"
                              "reports/\nsessions/*.tmp\n")
        gd = self.root / self.config["guards_dir"]
        gd.mkdir(exist_ok=True)
        conftest = gd / "conftest.py"
        if self.config["language"] == "python" and not conftest.exists():
            conftest.write_text(
                '"""Guards generated by Why. Each test enforces one decision in .why/decisions/."""\n'
            )

    def require(self) -> "Store":
        if not self.exists:
            raise StoreError(f"No .why/ store in {self.root}. Run `why init` first.")
        return self

    @property
    def config(self) -> dict[str, Any]:
        path = self.dir / "config.yaml"
        cfg = dict(DEFAULT_CONFIG)
        if path.exists():
            cfg.update(yaml.safe_load(path.read_text()) or {})
        return cfg

    # ---- decisions ---------------------------------------------------------

    def _path(self, decision_id: str) -> Path:
        return self.dir / "decisions" / f"{decision_id}.yaml"

    def decisions(self, status: str | Iterable[str] | None = None) -> list[Decision]:
        wanted = {status} if isinstance(status, str) else set(status) if status else None
        out = []
        for p in sorted((self.dir / "decisions").glob("D-*.yaml")):
            d = Decision.from_dict(yaml.safe_load(p.read_text()))
            if wanted is None or d.status in wanted:
                out.append(d)
        return out

    def get(self, decision_id: str) -> Decision:
        decision_id = normalize_id(decision_id)
        p = self._path(decision_id)
        if not p.exists():
            raise StoreError(f"No decision {decision_id}")
        return Decision.from_dict(yaml.safe_load(p.read_text()))

    def next_id(self) -> str:
        nums = [int(p.stem.split("-")[1]) for p in (self.dir / "decisions").glob("D-*.yaml")]
        return f"D-{(max(nums) + 1) if nums else 1:04d}"

    def save(self, d: Decision) -> Decision:
        d.updated_at = now()
        self._path(d.id).write_text(yaml.safe_dump(d.to_dict(), sort_keys=False, allow_unicode=True))
        return d

    def add(self, d: Decision, actor: str = "why") -> Decision:
        if not d.id:
            d.id = self.next_id()
        self.save(d)
        self.log_event(d.id, None, d.status, actor, note=f"created from {d.source.type}")
        return d

    def transition(self, decision_id: str, to: str, actor: str = "why", note: str = "") -> Decision:
        d = self.get(decision_id)
        if to == d.status:
            return d
        if to not in TRANSITIONS.get(d.status, set()):
            raise StoreError(f"{d.id}: cannot go from {d.status} to {to}")
        frm, d.status = d.status, to
        self.save(d)
        self.log_event(d.id, frm, to, actor, note)
        return d

    # ---- append-only logs --------------------------------------------------

    def log_event(self, decision_id: str, frm: str | None, to: str, actor: str, note: str = "") -> None:
        rec = {"ts": now(), "decision_id": decision_id, "from": frm, "to": to, "actor": actor, "note": note}
        with open(self.dir / "log.jsonl", "a") as f:
            f.write(json.dumps(rec) + "\n")

    def log(self, decision_id: str | None = None) -> list[dict[str, Any]]:
        rows = _read_jsonl(self.dir / "log.jsonl")
        if decision_id:
            rows = [r for r in rows if r["decision_id"] == normalize_id(decision_id)]
        return rows

    def add_evidence(self, ev: Evidence) -> None:
        with open(self.dir / "evidence.jsonl", "a") as f:
            f.write(json.dumps(ev.to_dict()) + "\n")

    def evidence(self, decision_id: str | None = None, limit: int | None = None) -> list[dict[str, Any]]:
        rows = _read_jsonl(self.dir / "evidence.jsonl")
        if decision_id:
            rows = [r for r in rows if r["decision_id"] == normalize_id(decision_id)]
        return rows[-limit:] if limit else rows

    def consults(self, limit: int = 200) -> list[dict[str, Any]]:
        """What agents asked Why over MCP (see mcp_server.py)."""
        return _read_jsonl(self.dir / "consults.jsonl")[-limit:]

    # ---- reports -----------------------------------------------------------

    def save_report(self, kind: str, name: str, data: dict[str, Any]) -> Path:
        safe = re.sub(r"[^A-Za-z0-9_.@-]+", "_", name)
        p = self.dir / "reports" / f"{kind}-{safe}.json"
        p.parent.mkdir(exist_ok=True)
        p.write_text(json.dumps(data, indent=2))
        return p

    def reports(self, kind: str | None = None) -> list[dict[str, Any]]:
        out = []
        for p in sorted((self.dir / "reports").glob(f"{kind or '*'}-*.json")):
            try:
                out.append(json.loads(p.read_text()))
            except json.JSONDecodeError:
                continue
        return sorted(out, key=lambda r: r.get("created_at", ""), reverse=True)


def normalize_id(s: str) -> str:
    s = s.strip().upper()
    if s.startswith("#"):
        s = s[1:]
    if s.isdigit():
        return f"D-{int(s):04d}"
    if s.startswith("D-") and s[2:].isdigit():
        return f"D-{int(s[2:]):04d}"
    return s


def _read_jsonl(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    rows = []
    for line in path.read_text().splitlines():
        line = line.strip()
        if line:
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError:
                continue
    return rows

"""Guard generation (F2): compile each approved decision into a runnable test."""

from __future__ import annotations

import re
import textwrap
from pathlib import Path

from .. import llm
from ..codeindex import CodeIndex
from ..models import Decision, GuardRef
from ..store import Store

SUPPORT_FILE = "_why_support.py"


class GuardError(RuntimeError):
    pass


def slug(text: str, n: int = 40) -> str:
    s = re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")
    if len(s) > n:
        s = s[: n + 1].rsplit("_", 1)[0] if "_" in s[:n] else s[:n]
    return s.rstrip("_") or "decision"


def js_framework(store: Store) -> str:
    """vitest or jest: config `test_runner`, else whichever the repo's package.json uses."""
    configured = store.config.get("test_runner")
    if configured:
        return configured
    pkg = store.root / "package.json"
    if pkg.exists():
        text = pkg.read_text()
        if '"vitest"' in text:
            return "vitest"
    return "jest"


def framework_for(store: Store) -> str:
    return "pytest" if store.config.get("language", "python") == "python" else js_framework(store)


def guard_filename(d: Decision, language: str = "python", framework: str = "jest") -> str:
    num = d.id.split("-")[1]
    if language == "python":
        return f"test_d{num}_{slug(d.title)}.py"
    return f"d{num}_{slug(d.title)}.test.{'ts' if framework == 'vitest' else 'js'}"


def decision_id_from_path(path: str) -> str | None:
    """D-0001 for a decision's guard; G-0001 for a published guarantee (registry or in-package)."""
    m = re.search(r"(?:^|test_)([dg])(\d{4})_", Path(path).name)
    return f"{m.group(1).upper()}-{m.group(2)}" if m else None


def ensure_support(store: Store) -> None:
    gd = store.root / store.config["guards_dir"]
    gd.mkdir(exist_ok=True)
    src = (Path(__file__).parent / "support_py.txt").read_text()
    target = gd / SUPPORT_FILE
    if not target.exists() or target.read_text() != src:
        target.write_text(src)


def _header(d: Decision) -> str:
    lines = [
        f"Why guard for {d.id}: {d.title}",
        "",
        f"Rule:   {d.rule}",
        f"Reason: {d.reason or '(none recorded)'}",
        f"Source: {d.source.type} {d.source.ref} {d.source.link}".rstrip(),
    ]
    if d.source.quote:
        lines.append(f'Quote:  "{d.source.quote}"')
    lines += ["", "Generated by Why. If this fails, either fix the code or supersede the decision:",
              f"    why supersede {d.id} --reason '...'"]
    return '"""' + "\n".join(lines).replace('"""', "'''") + '\n"""\n'


def _fail_msg(d: Decision) -> str:
    reason = f" Reason: {d.reason}" if d.reason else ""
    return f"Violates {d.id} ({d.title}).{reason}"


# ---- python templates ------------------------------------------------------------


def _py_call_count(d: Decision) -> str:
    p = d.params
    exc = p.get("raise") or "Exception"
    max_calls = int(p.get("max_calls", 1))
    overrides = p.get("entry_kwargs") or {}
    return _header(d) + textwrap.dedent(f"""
        import pytest

        from {SUPPORT_FILE[:-3]} import auto_args, bound_entry, call, patch_everywhere

        TARGET = {p['target']!r}
        ENTRY = {p['entry']!r}
        MAX_CALLS = {max_calls}


        def test_{d.id.replace('-', '').lower()}_{slug(d.title, 30)}():
            entry = bound_entry(ENTRY)
            calls = []

            def injected(*args, **kwargs):
                calls.append((args, kwargs))
                raise {exc}("injected by Why guard {d.id}")

            with patch_everywhere(TARGET, injected):
                args, kwargs = auto_args(entry, {overrides!r})
                try:
                    call(entry, *args, **kwargs)
                except BaseException:
                    pass  # the failure itself is expected; we only count attempts

            if not calls:
                pytest.fail(f"Guard setup: {{ENTRY}} never reached {{TARGET}}; regenerate this guard.")
            assert len(calls) <= MAX_CALLS, (
                f"{{TARGET}} was called {{len(calls)}} times after a {exc} (allowed: {{MAX_CALLS}}). "
                {_fail_msg(d)!r}
            )
        """)


def _py_returns(d: Decision) -> str:
    p = d.params
    mod, _, qual = p["target"].partition(":")
    name = qual.split(".")[-1]
    call_msg = p["call"].replace("{", "{{").replace("}", "}}")
    imports = f"from {mod} import {name}" if "." not in qual else (
        f"from {mod} import {qual.split('.')[0]}; {name} = {qual}")
    return _header(d) + textwrap.dedent(f"""
        import datetime  # noqa: F401  (available to the predicate)

        {imports}


        def test_{d.id.replace('-', '').lower()}_{slug(d.title, 30)}():
            result = {p['call']}
            assert {p['predicate']}, (
                f"{call_msg} returned {{result!r}}. "
                {_fail_msg(d)!r}
            )
        """)


def _py_forbid(d: Decision) -> str:
    p = d.params
    return _header(d) + textwrap.dedent(f"""
        from pathlib import Path

        from {SUPPORT_FILE[:-3]} import scan

        ROOT = Path(__file__).resolve().parent.parent
        PATTERN = {p['pattern']!r}
        PATHS = {p.get('paths') or ['.']!r}
        GLOB = {p.get('glob') or '*.py'!r}


        def test_{d.id.replace('-', '').lower()}_{slug(d.title, 30)}():
            hits = scan(ROOT, PATHS, GLOB, PATTERN)
            assert not hits, {_fail_msg(d)!r} + "\\n" + "\\n".join(hits)
        """)


def _js_forbid(d: Decision, framework: str = "jest") -> str:
    p = d.params
    if framework == "vitest":
        prelude = ('import { expect, test } from "vitest";\nimport fs from "node:fs";\nimport path from "node:path";\n'
                   'const ROOT = process.cwd();')
    else:
        prelude = 'const fs = require("fs");\nconst path = require("path");\nconst ROOT = path.resolve(__dirname, "..");'
    msg = f"Violates {d.id} ({d.title}). Reason: {d.reason}"
    expect_line = _js_assert("hits.length === 0", f"{msg!r} + '\\n' + hits.join('\\n')", framework)
    return f"// Why guard for {d.id}: {d.title}\n// Rule: {d.rule}\n// Reason: {d.reason}\n{prelude}\n" + textwrap.dedent(f"""
        const RX = new RegExp({p['pattern']!r}, "m");
        const SKIP = new Set(["node_modules", ".git", ".why", "why_guards", ".next", "dist", "build"]);
        function* walk(dir) {{
          for (const e of fs.readdirSync(dir, {{ withFileTypes: true }})) {{
            if (SKIP.has(e.name)) continue;
            const p = path.join(dir, e.name);
            if (e.isDirectory()) yield* walk(p);
            else if (/\\.(js|ts|jsx|tsx|mjs|cjs)$/.test(e.name)) yield p;
          }}
        }}
        test({(d.id + ': ' + d.title)!r}, () => {{
          const hits = [];
          for (const f of walk(ROOT)) {{
            fs.readFileSync(f, "utf8").split("\\n").forEach((line, i) => {{
              if (RX.test(line)) hits.push(`${{path.relative(ROOT, f)}}:${{i + 1}}: ${{line.trim()}}`);
            }});
          }}
          {expect_line}
        }});
        """).lstrip()


# ---- JS/TS templates (vitest or jest) ------------------------------------------------


def _js_assert(cond: str, msg: str, framework: str) -> str:
    """vitest's expect takes a message; jest's ignores it, so jest guards throw with the decision's reason."""
    if framework == "vitest":
        return f"expect({cond}, {msg}).toBe(true);"
    return f"if (!({cond})) throw new Error({msg});"


def _js_import_path(module: str, guards_dir: str) -> str:
    import posixpath

    rel = posixpath.relpath(module, guards_dir)
    return rel if rel.startswith(".") else f"./{rel}"


def _js_header(d: Decision) -> str:
    lines = [f"// Why guard for {d.id}: {d.title}", f"// Rule:   {d.rule}", f"// Reason: {d.reason or '(none recorded)'}",
             f"// Source: {d.source.type} {d.source.ref} {d.source.link}".rstrip()]
    if d.source.quote:
        lines.append(f"// Quote:  \"{d.source.quote}\"")
    lines.append(f"// Generated by Why. If this fails, fix the code or: why supersede {d.id} --reason '...'")
    return "\n".join(lines) + "\n"


ANY_ARG_JS = """// A stand-in for any argument: every property and call returns another stand-in.
const anyArg = ()__ANY__ =>
  new Proxy(function () {}, {
    get: (_t, k) => (k === "then" ? undefined : k === Symbol.toPrimitive ? () => 1 : k === "length" ? 0 : anyArg()),
    apply: () => anyArg(),
  });
"""


def _js_call_count(d: Decision, framework: str, guards_dir: str, entry_params: int) -> str:
    p = d.params
    t_mod, _, t_name = p["target"].partition(":")
    e_mod, _, e_name = p["entry"].partition(":")
    t_path, e_path = _js_import_path(t_mod, guards_dir), _js_import_path(e_mod, guards_dir)
    exc = p.get("raise") or "Error"
    max_calls = int(p.get("max_calls", 1))
    msg = _fail_msg(d)
    err = (f'Object.assign(new Error("{exc}: injected by Why guard {d.id}"), '
           f'{{ name: "{exc}", code: "{"ETIMEDOUT" if "imeout" in exc else "EWHY"}" }})')
    if framework == "vitest":
        mock = (f'import {{ expect, test, vi }} from "vitest";\n\n'
                f'vi.mock("{t_path}", async (importOriginal) => {{\n'
                f'  const mod = await importOriginal<Record<string, unknown>>();\n'
                f'  return {{ ...mod, {t_name}: vi.fn(() => {{ throw {err}; }}) }};\n}});\n')
    else:
        mock = (f'jest.mock("{t_path}", () => ({{\n  ...jest.requireActual("{t_path}"),\n'
                f'  {t_name}: jest.fn(() => {{ throw {err}; }}),\n}}));\n')
    ts = framework == "vitest"  # vitest guards are .ts; jest guards are plain .js
    cast = " as any" if ts else ""
    imports = (f'import * as target from "{t_path}";\nimport {{ {e_name} }} from "{e_path}";' if ts else
               f'const target = require("{t_path}");\nconst {{ {e_name} }} = require("{e_path}");')
    return _js_header(d) + mock + f"""
{imports}

{ANY_ARG_JS.replace("__ANY__", ": any" if ts else "")}
test({(d.id + ": " + d.title)!r}, async () => {{
  try {{
    await ({e_name}{cast})(...Array.from({{ length: {max(entry_params, 1)} }}, anyArg));
  }} catch {{
    // the injected failure itself is expected; we only count attempts
  }}
  const calls = (target.{t_name}{cast}).mock.calls.length;
  {_js_assert("calls > 0", f'"Guard setup: {e_name}() never reached {t_name}(); regenerate this guard"', framework)}
  {_js_assert(f"calls <= {max_calls}", f"`{t_name}() was called ${{calls}} times after a {exc} (allowed: {max_calls}). ` + {msg!r}", framework)}
}}, 30_000);
"""


def _js_returns(d: Decision, framework: str, guards_dir: str) -> str:
    p = d.params
    mod, _, name = p["target"].partition(":")
    path = _js_import_path(mod, guards_dir)
    ts = framework == "vitest"
    call_msg = p["call"].replace("`", "'").replace("${", "\\${")
    head = 'import { expect, test } from "vitest";\n' if ts else ""
    imp = f'import {{ {name} }} from "{path}";' if ts else f'const {{ {name} }} = require("{path}");'
    return _js_header(d) + head + f"""{imp}

test({(d.id + ": " + d.title)!r}, async () => {{
  const result{": any" if ts else ""} = await {p['call']};
  {_js_assert(p['predicate'], f"`{call_msg} returned ${{JSON.stringify(result)}}. ` + {_fail_msg(d)!r}", framework)}
}});
"""


# ---- model-written guards (Nemotron Super) ------------------------------------------

SUPER_SYSTEM = """You write ONE guard test that enforces an engineering decision in an existing repo.
The test must FAIL if the code breaks the decision and PASS on code that keeps it.
Rules:
- Test behaviour through the repo's real functions; mock only external I/O (network, payment gateways, clocks).
- Keep it deterministic: no network, no sleeps, no randomness.
- Use only the standard library and {framework}.{js_note}
- Put the decision id and its reason in the assertion message.
- Python: helpers are available via `from _why_support import resolve, patch_everywhere, auto_args, call, scan`.
Return only the test file in one fenced code block."""


def _model_guard(store: Store, d: Decision, index: CodeIndex, language: str) -> str:
    framework = framework_for(store)
    files = list(dict.fromkeys(d.scope.get("files", [])))[:4]
    code = "\n\n".join(f"# FILE: {f}\n{(store.root / f).read_text(errors='replace')[:6000]}" for f in files
                       if (store.root / f).exists())
    user = (
        f"DECISION {d.id}: {d.title}\nRule: {d.rule}\nReason: {d.reason}\nSource quote: {d.source.quote}\n"
        f"Guard file will live at {store.config['guards_dir']}/ (repo root is its parent; python path: "
        f"{store.config.get('python_path')}).\n\nCODE INDEX:\n{index.summary(150)}\n\nRELEVANT FILES:\n{code}"
    )
    js_note = ("\n- vitest: import { describe, test, expect, vi } from \"vitest\"; the file is TypeScript and runs from "
               "the repo root; import repo code with relative paths from the guard file.") if framework == "vitest" else ""
    text = llm.chat("super", SUPER_SYSTEM.format(framework=framework, js_note=js_note), user, max_tokens=3000)
    body = llm.extract_code(text)
    if language == "python":
        compile(body, "guard", "exec")  # reject syntax errors early
        return _header(d) + "\n" + body
    return body


def generate(store: Store, d: Decision, index: CodeIndex | None = None, use_model: bool | None = None) -> GuardRef:
    language = store.config.get("language", "python")
    framework = framework_for(store)
    templates = {"call_count": _py_call_count, "returns": _py_returns, "forbid_pattern": _py_forbid}
    if language == "python":
        ensure_support(store)
    else:
        gd = store.config["guards_dir"]
        (store.root / gd).mkdir(exist_ok=True)

        def entry_params(dec: Decision) -> int:
            from ..mine import index_for

            hits = (index or index_for(store)).find(dec.params.get("entry", "").split(":")[-1])
            return len(hits[0].params) if hits else 1

        templates = {
            "forbid_pattern": lambda dec: _js_forbid(dec, framework),
            "call_count": lambda dec: _js_call_count(dec, framework, gd, entry_params(dec)),
            "returns": lambda dec: _js_returns(dec, framework, gd),
        }
    use_model = llm.available() if use_model is None else use_model
    if d.kind in templates:
        src, by = templates[d.kind](d), "template"
    elif use_model:
        from ..mine import index_for

        src, by = _model_guard(store, d, index or index_for(store), language), "nemotron-super"
    else:
        raise GuardError(
            f"{d.id} is a '{d.kind}' decision: it needs Nemotron Super (set NEBIUS_API_KEY) or a "
            f"hand-written guard at {store.config['guards_dir']}/{guard_filename(d, language, framework)}"
        )
    rel = f"{store.config['guards_dir']}/{guard_filename(d, language, framework)}"
    (store.root / rel).write_text(src)
    return GuardRef(path=rel, language=language, framework=framework, generated_by=by)


def adopt_existing(store: Store, d: Decision) -> GuardRef | None:
    """A human may write the guard by hand; pick it up by its filename."""
    language = store.config.get("language", "python")
    gd = store.root / store.config["guards_dir"]
    num = d.id.split("-")[1]
    for f in gd.glob(f"*d{num}_*"):
        return GuardRef(path=f.relative_to(store.root).as_posix(), language=language,
                        framework=framework_for(store), generated_by="human")
    return None
